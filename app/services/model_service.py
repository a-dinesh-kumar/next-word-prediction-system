
import json
import pickle
from pathlib import Path

import numpy as np
import tensorflow as tf
from tensorflow.keras.preprocessing.sequence import pad_sequences


class ModelService:
    """Loads the model artifacts and provides shared inference methods."""

    def __init__(
        self,
        model_path: Path,
        tokenizer_path: Path,
        metadata_path: Path,
    ):
        self.model_path = model_path
        self.tokenizer_path = tokenizer_path
        self.metadata_path = metadata_path

        self.model = None
        self.tokenizer = None
        self.metadata = None
        self.id_to_word = None

        self.max_sequence_length = None
        self.vocab_size = None
        self.oov_token_id = None

    def load(self):
        """Load and validate all required artifacts."""

        for path in (
            self.model_path,
            self.tokenizer_path,
            self.metadata_path,
        ):
            if not path.is_file():
                raise FileNotFoundError(
                    f"Required artifact not found: {path}"
                )

        # Only load pickle files generated by our trusted training pipeline.
        with self.tokenizer_path.open("rb") as file:
            tokenizer = pickle.load(file)

        with self.metadata_path.open("r", encoding="utf-8") as file:
            metadata = json.load(file)

        model = tf.keras.models.load_model(
            self.model_path,
            compile=False,
        )

        max_sequence_length = int(metadata["max_sequence_length"])
        vocab_size = int(metadata["effective_vocab_size"])
        oov_token = metadata["oov_token"]
        oov_token_id = tokenizer.word_index.get(oov_token)

        if oov_token_id is None:
            raise ValueError("The configured OOV token is missing.")

        if model.input_shape[-1] != max_sequence_length:
            raise ValueError(
                "Model input length does not match metadata."
            )

        if model.output_shape[-1] != vocab_size:
            raise ValueError(
                "Model output size does not match metadata."
            )

        self.model = model
        self.tokenizer = tokenizer
        self.metadata = metadata
        self.max_sequence_length = max_sequence_length
        self.vocab_size = vocab_size
        self.oov_token_id = int(oov_token_id)

        self.id_to_word = {
            int(token_id): word
            for word, token_id in tokenizer.word_index.items()
            if int(token_id) < vocab_size
        }

        return self

    @property
    def is_loaded(self):
        return (
            self.model is not None
            and self.tokenizer is not None
            and self.metadata is not None
        )

    def encode_text(self, text: str):
        """Tokenize input and return IDs plus OOV statistics."""

        token_sequences = self.tokenizer.texts_to_sequences([text])
        token_ids = token_sequences[0]

        if not token_ids:
            raise ValueError(
                "Input contains no tokens recognized by the tokenizer."
            )

        oov_count = sum(
            token_id == self.oov_token_id
            for token_id in token_ids
        )

        padded_input = pad_sequences(
            [token_ids],
            maxlen=self.max_sequence_length,
            padding="post",
            truncating="pre",
        )

        return {
            "token_ids": token_ids,
            "padded_input": padded_input,
            "oov_count": oov_count,
            "oov_ratio": oov_count / len(token_ids),
        }

    def predict_probabilities(self, token_ids):
        """Predict next-word probabilities for a token sequence."""

        context = token_ids[-self.max_sequence_length:]

        padded_context = pad_sequences(
            [context],
            maxlen=self.max_sequence_length,
            padding="post",
            truncating="pre",
        )

        probabilities = self.model.predict(
            padded_context,
            verbose=0,
        )[0].astype(np.float64)

        # Padding is never a valid next word.
        probabilities[0] = 0.0

        return probabilities
